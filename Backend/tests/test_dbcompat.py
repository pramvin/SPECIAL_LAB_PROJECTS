"""Run from Backend/:  .venv/bin/python -m unittest tests.test_dbcompat -v

Covers the SQLite -> Postgres translation as pure string functions (no Postgres server needed)
and the engine switch rules. The live Postgres path needs a real DATABASE_URL to verify.
"""
import os
import unittest
from unittest import mock

from app import dbcompat
from app.main import SCHEMA as MAIN_SCHEMA


class Translate(unittest.TestCase):
    def test_placeholders_and_percent(self):
        self.assertEqual(dbcompat.to_pg_sql("SELECT 1 WHERE a = ? AND b LIKE '50%'"),
                         "SELECT 1 WHERE a = %s AND b LIKE '50%%'")

    def test_identity_only_for_plain_id(self):
        out = dbcompat.to_pg_ddl("id INTEGER PRIMARY KEY, user_id INTEGER PRIMARY KEY REFERENCES users(id)")
        self.assertIn("id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", out)
        self.assertIn("user_id BIGINT PRIMARY KEY REFERENCES", out)
        self.assertNotIn("user_id BIGINT GENERATED", out)

    def test_types_and_comments(self):
        out = dbcompat.to_pg_ddl("a INTEGER, b REAL, -- note; with semicolon\n c TEXT")
        self.assertIn("a BIGINT", out)
        self.assertIn("b DOUBLE PRECISION", out)
        self.assertNotIn("note", out)

    def test_whole_app_schema_has_no_sqlite_types_left(self):
        out = dbcompat.to_pg_ddl(MAIN_SCHEMA)
        self.assertNotRegex(out, r"\bINTEGER\b|\bREAL\b|AUTOINCREMENT")
        stmts = dbcompat.split_script(out)
        self.assertTrue(all(s.startswith("CREATE") for s in stmts))

    def test_pgrow_index_and_name(self):
        row = dbcompat.PgRow((1, "a"))
        row._cols = ("id", "name")
        self.assertEqual((row[0], row["name"], row.keys()), (1, "a", ["id", "name"]))
        self.assertEqual(dict(row), {"id": 1, "name": "a"})


class Engine(unittest.TestCase):
    def test_planwise_db_forces_sqlite(self):
        env = {"PLANWISE_DB": "/tmp/x.db", "DATABASE_URL": "postgresql://u:p@h/d"}
        with mock.patch.dict(os.environ, env):
            self.assertIsNone(dbcompat.database_url())

    def test_database_url_selects_postgres(self):
        with mock.patch.dict(os.environ, {"DATABASE_URL": "postgresql://u:p@h/d"}):
            os.environ.pop("PLANWISE_DB", None)
            self.assertEqual(dbcompat.database_url(), "postgresql://u:p@h/d")

    def test_sqlite_helpers(self):
        with mock.patch.dict(os.environ, {"PLANWISE_DB": ":memory:"}):
            conn = dbcompat.connect(":memory:")
        conn.executescript("CREATE TABLE t (a INTEGER PRIMARY KEY, b TEXT);")
        self.assertEqual(dbcompat.table_names(conn), {"t"})
        self.assertEqual(dbcompat.column_names(conn, "t"), {"a", "b"})
        conn.execute("INSERT INTO t (b) VALUES (?)", ("x",))
        self.assertEqual(dbcompat.read_df(conn, "SELECT a, b FROM t").to_dict("records"), [{"a": 1, "b": "x"}])


if __name__ == "__main__":
    unittest.main()
