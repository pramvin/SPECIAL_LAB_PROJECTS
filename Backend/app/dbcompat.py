"""One place that decides SQLite vs Postgres.

- `PLANWISE_DB` set          -> always SQLite at that path (safe for tests on a copy).
- else `DATABASE_URL` set    -> Postgres (Neon on Render).
- neither                    -> SQLite at the module's default path (local dev).

SQL elsewhere is written once, in the portable subset both engines accept:
`?` placeholders, `ON CONFLICT ... DO UPDATE/NOTHING`, `RETURNING id`. This module only
translates what cannot be portable: placeholders, DDL column types, and table/column lookups.
"""
import os
import re
import sqlite3

import pandas as pd


def database_url() -> str | None:
    if os.environ.get("PLANWISE_DB"):
        return None
    url = os.environ.get("DATABASE_URL", "").strip()
    return url if url.startswith(("postgres://", "postgresql://")) else None


def to_pg_sql(sql: str) -> str:
    """`?` -> `%s` (literal `%` doubled so psycopg does not read it as a placeholder)."""
    return sql.replace("%", "%%").replace("?", "%s")


def to_pg_ddl(sql: str) -> str:
    """SQLite column types -> Postgres. INTEGER becomes BIGINT (share volume overflows 32 bits)."""
    sql = re.sub(r"--[^\n]*", "", sql)
    sql = re.sub(r"(?<!\w)id INTEGER PRIMARY KEY", "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", sql)
    sql = re.sub(r"\bINTEGER\b", "BIGINT", sql)
    return re.sub(r"\bREAL\b", "DOUBLE PRECISION", sql)


def split_script(script: str) -> list[str]:
    return [s.strip() for s in re.sub(r"--[^\n]*", "", script).split(";") if s.strip()]


class PgRow(tuple):
    """Row readable by index and by column name, like sqlite3.Row."""

    _cols: tuple = ()

    def __getitem__(self, key):
        if isinstance(key, str):
            return tuple.__getitem__(self, self._cols.index(key))
        return tuple.__getitem__(self, key)

    def keys(self) -> list[str]:
        return list(self._cols)


def _row_factory(cursor):
    cols = tuple(c.name for c in cursor.description) if cursor.description else ()

    def make(values):
        row = PgRow(values)
        row._cols = cols
        return row

    return make


class PgConnection:
    """The slice of the sqlite3.Connection API this project uses, on top of psycopg."""

    def __init__(self, raw, url: str | None = None):
        self._raw = raw
        self._url = url

    def _reconnect(self) -> None:
        """Neon drops a connection that sat idle (a 20-minute AI review holds one open): open a new one."""
        try:
            self._raw.close()
        except Exception:  # noqa: BLE001 - it is already dead
            pass
        self._raw = psycopg.connect(self._url, **_CONNECT_ARGS)

    def _retry(self, fn):
        try:
            return fn()
        except psycopg.OperationalError:
            if not self._url:
                raise
            self._reconnect()
            return fn()

    def execute(self, sql: str, params=None):
        head = sql.lstrip()[:6].upper()
        if head in ("CREATE", "ALTER "):
            sql = to_pg_ddl(sql)

        def run():
            cur = self._raw.cursor()
            if params:
                cur.execute(to_pg_sql(sql), params)
            else:
                cur.execute(sql)
            return cur

        return self._retry(run)

    def executemany(self, sql: str, seq):
        cur = self._raw.cursor()
        cur.executemany(to_pg_sql(sql), seq)
        return cur

    def executescript(self, script: str) -> None:
        cur = self._raw.cursor()
        for stmt in split_script(to_pg_ddl(script)):
            cur.execute(stmt)
        self._raw.commit()

    def commit(self) -> None:
        self._raw.commit()

    def rollback(self) -> None:
        try:
            self._raw.rollback()
        except psycopg.OperationalError:
            if not self._url:
                raise
            self._reconnect()  # the dead connection's open transaction is gone with it

    def close(self) -> None:
        self._raw.close()

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc, tb):
        # Same contract as `with sqlite3_conn:` - commit or roll back, keep the connection open.
        if exc_type is None:
            self._raw.commit()
        else:
            self.rollback()
        return False


